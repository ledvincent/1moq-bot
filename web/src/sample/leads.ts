interface Seed {
  id: string;
  name: string;
  slug: string;
  instagram: string | null;
  email: boolean;
  clientType: ClientType;
  clientTypeReason: string;
  city: string;
  market: string;
  language: Language;
  timeZone: string | null;
  status: LeadStatus;
  statusDate: string;
  fit: FitLevel;
  rules: RuleResult[];
  flags?: string[];
  followers: string;
  founder: string;
  history: HistoryEntry[];
}

function lead(seed: Seed): Lead {
  return {
    id: seed.id,
    name: seed.name,
    website: `https://${seed.slug}.example`,
    instagram: seed.instagram,
    email: seed.email ? `${seed.slug}@example.com` : null,
    clientType: seed.clientType,
    clientTypeReason: seed.clientTypeReason,
    market: seed.market,
    language: seed.language,
    timeZone: seed.timeZone,
    status: seed.status,
    statusDate: seed.statusDate,
    fit: seed.fit,
    rules: seed.rules,
    flags: seed.flags ?? [],
    facts: [
      { fact: 'Address', value: `${seed.city}, ${seed.market}`, source: 'Google Maps' },
      { fact: 'Website', value: `https://${seed.slug}.example`, source: 'Google Maps' },
      {
        fact: 'Email address',
        value: seed.email ? `${seed.slug}@example.com` : 'not found',
        source: 'website',
      },
      { fact: 'Instagram followers', value: seed.followers, source: 'Instagram profile' },
      { fact: 'Founder', value: seed.founder, source: 'AI profile' },
      { fact: 'Client type', value: seed.clientType, source: 'AI profile' },
      { fact: 'Language', value: seed.language, source: 'website' },
      { fact: 'Time zone', value: seed.timeZone ?? 'not known', source: 'Google Maps' },
    ],
    history: seed.history,
  };
}

